export function generateAsciiArt(text: string, font: AsciiFont = 'standard'): string {
  const clean = text.toUpperCase();
  if (!clean) return '';

  const fontMap = font === 'blocks' ? BLOCKS_FONT : STANDARD_FONT;
  const lineCount = font === 'blocks' ? 3 : 4;
  const lines: string[] = Array.from({ length: lineCount }, () => '');

  for (const char of clean) {
    const glyph = fontMap[char] || fontMap['?'] || Array(lineCount).fill(char);
    for (let i = 0; i < lineCount; i++) {
      lines[i] += (glyph[i] || '  ') + ' ';
    }
  }

  return lines.join('\n');
}
